package DAY2;

public class Swappingnumbers {
	
	public static void main(String a[]) {
		
		// Swapping 2 numbers using +, - Operators
		
		int x = 10, y = 22;
		System.out.println("x = "+ x);
		System.out.println("y = "+ y);
		x = x+y;
		y = x-y;
		x = x-y;
		System.out.println("Values after swaspping are below");
		System.out.println("x = " + x);
		System.out.println("y = " + y);
		
		
		
		
	}

}
